import hashlib
import json
import random
import secrets
from datetime import datetime, timedelta

from cc_console.datasource import choose_test_host, default_port, normalize_ds_type

from .base import AdapterCapabilityError, DatabaseAdapter, parse_host_port, require_temp_schema


CORE_TABLES = ("pk_int_table", "pk_int_auto_table", "pk_varchar_table", "pk_timestamp_table")


def json_digest_row(row):
    return json.dumps([str(item) if item is not None else None for item in row], ensure_ascii=False, separators=(",", ":")).encode("utf-8")


class DbApiRdbAdapter(DatabaseAdapter):
    can_init_source = True
    can_prepare_target = True
    can_cleanup = True
    can_faker_crud = True
    can_compare = True
    namespace_kind = "schema"
    identifier_quote = '"'
    paramstyle = "format"
    default_database = None
    default_schema = None
    int_type = "INTEGER"
    varchar_type = "VARCHAR(255)"
    code_type = "VARCHAR(64)"
    decimal_type = "DECIMAL(18,2)"
    timestamp_type = "TIMESTAMP"
    current_timestamp = "CURRENT_TIMESTAMP"
    auto_id_type = "INTEGER GENERATED BY DEFAULT AS IDENTITY"
    create_table_suffix = ""
    count_select_suffix = ""
    supports_order_by_all = True

    def _quote_ident(self, name):
        quote = self.identifier_quote
        return quote + str(name).replace(quote, quote + quote) + quote

    def _qname(self, schema, table):
        if self.namespace_kind == "database":
            return self._quote_ident(table)
        return self._quote_ident(schema) + "." + self._quote_ident(table)

    def _placeholder(self, index):
        if self.paramstyle == "qmark":
            return "?"
        if self.paramstyle == "numeric":
            return ":" + str(index)
        return "%s"

    def _placeholders(self, count):
        return ", ".join(self._placeholder(i + 1) for i in range(count))

    def _execute(self, cur, sql, params=None):
        if params is None:
            return cur.execute(sql)
        return cur.execute(sql, tuple(params))

    def _fetchone(self, cur):
        row = cur.fetchone()
        return row

    def _fetchall(self, cur):
        return cur.fetchall()

    def _rowcount(self, cur):
        value = getattr(cur, "rowcount", 0)
        return 0 if value in (None, -1) else value

    def _ds_database(self, ds, fallback=None):
        for key in ("dbName", "databaseName", "database", "defaultDb", "sid", "serviceName"):
            if ds.get(key):
                return ds.get(key)
        return fallback or self.default_database

    def _account(self, ds, user=None):
        account = user or ds.get("accountName")
        if not account and self.name != "duckdb-family":
            raise ValueError("datasource accountName is empty, dataSourceId=" + str(ds.get("id")))
        return account

    def _host_port(self, ds, host_type=None, host=None):
        ds_type = normalize_ds_type(ds.get("dataSourceType") or ds.get("type"))
        host_value, _resolved_host_type = choose_test_host(ds, host_type, host)
        return parse_host_port(host_value, default_port(ds_type))

    def _connect(self, ds, password, user=None, db=None, host_type=None, host=None):
        raise AdapterCapabilityError(self.name + " does not implement connection")

    def _connect_namespace(self, ds, password, schema, user=None, host_type=None, host=None):
        db = schema if self.namespace_kind == "database" else self._ds_database(ds)
        return self._connect(ds, password, user=user, db=db, host_type=host_type, host=host)

    def _close(self, conn):
        conn.close()

    def _close_cursor(self, cur):
        try:
            cur.close()
        except Exception:
            pass

    def _commit(self, conn):
        try:
            conn.commit()
        except Exception:
            pass

    def _drop_namespace(self, cur, schema):
        if self.namespace_kind == "database":
            self._execute(cur, "DROP DATABASE IF EXISTS " + self._quote_ident(schema))
        else:
            self._execute(cur, "DROP SCHEMA IF EXISTS " + self._quote_ident(schema) + " CASCADE")

    def _create_namespace(self, cur, schema):
        if self.namespace_kind == "database":
            self._execute(cur, "CREATE DATABASE " + self._quote_ident(schema))
        else:
            self._execute(cur, "CREATE SCHEMA IF NOT EXISTS " + self._quote_ident(schema))

    def _drop_table(self, cur, schema, table):
        self._execute(cur, "DROP TABLE IF EXISTS " + self._qname(schema, table))

    def _create_table_sql(self, schema, table):
        id_sql = self.auto_id_type if table == "pk_int_auto_table" else self.int_type + " NOT NULL"
        if table == "pk_varchar_table":
            id_sql = self.code_type + " NOT NULL"
        elif table == "pk_timestamp_table":
            id_sql = self.timestamp_type + " NOT NULL"
        return (
            "CREATE TABLE "
            + self._qname(schema, table)
            + " ("
            + "id "
            + id_sql
            + ", code "
            + self.code_type
            + " NOT NULL, amount "
            + self.decimal_type
            + " NULL, payload "
            + self.varchar_type
            + " NULL, updated_at "
            + self.timestamp_type
            + " DEFAULT "
            + self.current_timestamp
            + ", PRIMARY KEY (id))"
            + self.create_table_suffix
        )

    def _table_ddls(self, profile):
        if profile != self.default_profile:
            raise AdapterCapabilityError("unsupported " + self.name + " profile: " + str(profile))
        return [(table, self._create_table_sql("{schema}", table)) for table in CORE_TABLES]

    def profile_tables(self, profile):
        if profile != self.default_profile:
            raise AdapterCapabilityError("unsupported " + self.name + " profile: " + str(profile))
        return list(CORE_TABLES)

    def init_source_dataset(self, ds, password, schema, rows, profile, drop_existing, allow_non_temp, **kwargs):
        ds_type = normalize_ds_type(ds.get("dataSourceType") or ds.get("type"))
        if not self.supports_source(ds_type):
            raise AdapterCapabilityError(self.name + " source init does not support " + ds_type)
        require_temp_schema(schema, allow_non_temp)
        self.profile_tables(profile)
        root = self._connect(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = root.cursor()
            try:
                if drop_existing:
                    self._drop_namespace(cur, schema)
                self._create_namespace(cur, schema)
            finally:
                self._close_cursor(cur)
            self._commit(root)
        finally:
            self._close(root)

        conn = self._connect_namespace(ds, password, schema, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = conn.cursor()
            try:
                for table in self.profile_tables(profile):
                    self._drop_table(cur, schema, table)
                    self._execute(cur, self._create_table_sql(schema, table))
                    self._seed_table(cur, schema, table, rows)
            finally:
                self._close_cursor(cur)
            self._commit(conn)
        finally:
            self._close(conn)
        return {"schema": schema, "profile": profile, "tables": self.profile_tables(profile), "seedRowsPerTable": rows}

    def prepare_target_dataset(self, ds, password, schema, drop_existing, allow_non_temp, **kwargs):
        ds_type = normalize_ds_type(ds.get("dataSourceType") or ds.get("type"))
        if not self.supports_target(ds_type):
            raise AdapterCapabilityError(self.name + " target prepare does not support " + ds_type)
        require_temp_schema(schema, allow_non_temp)
        conn = self._connect(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = conn.cursor()
            try:
                if drop_existing:
                    self._drop_namespace(cur, schema)
                self._create_namespace(cur, schema)
            finally:
                self._close_cursor(cur)
            self._commit(conn)
        finally:
            self._close(conn)
        return {"schema": schema}

    def cleanup_dataset(self, ds, password, schema, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        conn = self._connect(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = conn.cursor()
            try:
                self._drop_namespace(cur, schema)
            finally:
                self._close_cursor(cur)
            self._commit(conn)
        finally:
            self._close(conn)
        return {"schema": schema, "dropped": True}

    def _insert_sql(self, schema, table, columns):
        return (
            "INSERT INTO "
            + self._qname(schema, table)
            + " ("
            + ", ".join(self._quote_ident(col) for col in columns)
            + ") VALUES ("
            + self._placeholders(len(columns))
            + ")"
        )

    def _seed_table(self, cur, schema, table, rows):
        if table == "pk_int_auto_table":
            sql = self._insert_sql(schema, table, ("code", "amount", "payload"))
            for i in range(1, rows + 1):
                self._execute(cur, sql, ("code_" + str(i), i * 1.11, "seed-" + table + "-" + str(i)))
        elif table == "pk_varchar_table":
            sql = self._insert_sql(schema, table, ("id", "code", "amount", "payload"))
            for i in range(1, rows + 1):
                self._execute(cur, sql, ("vk_" + str(i), "code_" + str(i), i * 1.11, "seed-" + table + "-" + str(i)))
        elif table == "pk_timestamp_table":
            sql = self._insert_sql(schema, table, ("id", "code", "amount", "payload"))
            base = datetime(2026, 1, 1, 0, 0, 0)
            for i in range(1, rows + 1):
                self._execute(cur, sql, (base + timedelta(seconds=i), "code_" + str(i), i * 1.11, "seed-" + table + "-" + str(i)))
        else:
            sql = self._insert_sql(schema, table, ("id", "code", "amount", "payload"))
            for i in range(1, rows + 1):
                self._execute(cur, sql, (i, "code_" + str(i), i * 1.11, "seed-" + table + "-" + str(i)))

    def faker_crud(self, ds, password, schema, rounds, profile, seed, allow_non_temp, **kwargs):
        ds_type = normalize_ds_type(ds.get("dataSourceType") or ds.get("type"))
        if not self.supports_source(ds_type):
            raise AdapterCapabilityError(self.name + " faker CRUD does not support " + ds_type)
        require_temp_schema(schema, allow_non_temp)
        tables = self.profile_tables(profile)
        rng = random.Random(seed)
        stats = {table: {"insert": 0, "update": 0, "delete": 0, "skippedDuplicate": 0} for table in tables}
        changed = 0
        conn = self._connect_namespace(ds, password, schema, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = conn.cursor()
            try:
                for i in range(1, rounds + 1):
                    table = rng.choice(tables)
                    action = rng.choice(("insert", "update", "delete"))
                    marker = "crud-" + str(seed) + "-" + str(i)
                    try:
                        affected = self._crud_one(cur, schema, table, action, marker, i, rng)
                    except Exception as e:
                        if self._is_duplicate_key_error(e):
                            stats[table]["skippedDuplicate"] += 1
                            continue
                        raise
                    stats[table][action] += 1
                    changed += int(affected or 0)
            finally:
                self._close_cursor(cur)
            self._commit(conn)
        finally:
            self._close(conn)
        return {"schema": schema, "profile": profile, "rounds": rounds, "seed": seed, "changedRows": changed, "stats": stats, "ok": changed > 0}

    def _is_duplicate_key_error(self, error):
        text = str(error).lower()
        return "duplicate" in text or "unique constraint" in text or "primary key" in text

    def _update_sql(self, schema, table, id_expr):
        return "UPDATE " + self._qname(schema, table) + " SET " + self._quote_ident("payload") + " = " + self._placeholder(1) + " WHERE " + self._quote_ident("id") + " = " + id_expr

    def _delete_sql(self, schema, table, id_expr):
        return "DELETE FROM " + self._qname(schema, table) + " WHERE " + self._quote_ident("id") + " = " + id_expr

    def _crud_one(self, cur, schema, table, action, marker, i, rng):
        if table == "pk_int_auto_table":
            if action == "insert":
                self._execute(cur, self._insert_sql(schema, table, ("code", "amount", "payload")), (marker, i * 2.22, marker))
            elif action == "update":
                self._execute(cur, self._update_sql(schema, table, self._placeholder(2)), (marker, rng.randint(1, 50)))
            else:
                self._execute(cur, self._delete_sql(schema, table, self._placeholder(1)), (rng.randint(1, 50),))
            return self._rowcount(cur)
        if table == "pk_varchar_table":
            if action == "insert":
                self._execute(cur, self._insert_sql(schema, table, ("id", "code", "amount", "payload")), ("crud_vk_" + str(i), marker, i * 2.22, marker))
            elif action == "update":
                self._execute(cur, self._update_sql(schema, table, self._placeholder(2)), (marker, "vk_" + str(rng.randint(1, 50))))
            else:
                self._execute(cur, self._delete_sql(schema, table, self._placeholder(1)), ("vk_" + str(rng.randint(1, 50)),))
            return self._rowcount(cur)
        if table == "pk_timestamp_table":
            base = datetime(2026, 1, 1, 0, 0, 0)
            crud_base = datetime(2027, 1, 1, 0, 0, 0)
            if action == "insert":
                self._execute(cur, self._insert_sql(schema, table, ("id", "code", "amount", "payload")), (crud_base + timedelta(seconds=i), marker, i * 2.22, marker))
            elif action == "update":
                self._execute(cur, self._update_sql(schema, table, self._placeholder(2)), (marker, base + timedelta(seconds=rng.randint(1, 50))))
            else:
                self._execute(cur, self._delete_sql(schema, table, self._placeholder(1)), (base + timedelta(seconds=rng.randint(1, 50)),))
            return self._rowcount(cur)
        if action == "insert":
            self._execute(cur, self._insert_sql(schema, table, ("id", "code", "amount", "payload")), (100000 + i, marker, i * 2.22, marker))
        elif action == "update":
            self._execute(cur, self._update_sql(schema, table, self._placeholder(2)), (marker, rng.randint(1, 50)))
        else:
            self._execute(cur, self._delete_sql(schema, table, self._placeholder(1)), (rng.randint(1, 50),))
        return self._rowcount(cur)

    def _columns(self, cur, schema, table):
        try:
            self._execute(cur, "SELECT * FROM " + self._qname(schema, table) + " WHERE 1=0")
        except Exception:
            return []
        return [item[0] for item in (cur.description or [])]

    def _table_count(self, cur, schema, table):
        try:
            self._execute(cur, "SELECT COUNT(*) FROM " + self._qname(schema, table) + self.count_select_suffix)
            row = self._fetchone(cur)
            return {"exists": True, "rows": row[0] if row else 0}
        except Exception:
            return {"exists": False, "rows": 0}

    def _table_digest(self, cur, schema, table):
        columns = self._columns(cur, schema, table)
        if not columns:
            return {"exists": False, "rows": 0, "digest": None, "columns": []}
        col_sql = ", ".join(self._quote_ident(col) for col in columns)
        order_sql = " ORDER BY " + col_sql if self.supports_order_by_all else ""
        self._execute(cur, "SELECT " + col_sql + " FROM " + self._qname(schema, table) + order_sql)
        digest = hashlib.sha256()
        count = 0
        for row in self._fetchall(cur):
            digest.update(json_digest_row(row))
            digest.update(b"\n")
            count += 1
        return {"exists": True, "rows": count, "digest": digest.hexdigest(), "columns": columns}

    def table_snapshot(self, ds, password, schema, table, check_mode, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        conn = self._connect_namespace(ds, password, schema, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        try:
            cur = conn.cursor()
            try:
                if check_mode == "digest":
                    return self._table_digest(cur, schema, table)
                if check_mode == "count":
                    return self._table_count(cur, schema, table)
                raise ValueError("unsupported check mode: " + str(check_mode))
            finally:
                self._close_cursor(cur)
        finally:
            self._close(conn)

    def compare_datasets(self, source_ds, target_ds, source_password, target_password, source_schema, target_schema, profile, allow_non_temp, **kwargs):
        check_mode = kwargs.get("check_mode") or "count"
        tables = kwargs.get("tables") or self.profile_tables(profile)
        result = {"sourceSchema": source_schema, "targetSchema": target_schema, "profile": profile, "checkMode": check_mode, "tables": [], "ignoredTables": [], "ok": True}
        for table in tables:
            src = self.table_snapshot(source_ds, source_password, source_schema, table, check_mode, allow_non_temp, user=kwargs.get("source_user"), host_type=kwargs.get("source_host_type"), host=kwargs.get("source_host"))
            dst = self.table_snapshot(target_ds, target_password, target_schema, table, check_mode, allow_non_temp, user=kwargs.get("target_user"), host_type=kwargs.get("target_host_type"), host=kwargs.get("target_host"))
            ok = snapshots_equal(src, dst, check_mode)
            result["tables"].append({"table": table, "ok": ok, "source": src, "target": dst, "primaryKeyColumns": ["id"]})
            if not ok:
                result["ok"] = False
        return result


def snapshots_equal(src, dst, check_mode):
    if check_mode == "digest":
        return src.get("exists") == dst.get("exists") and src.get("rows") == dst.get("rows") and src.get("digest") == dst.get("digest")
    return src.get("exists") == dst.get("exists") and src.get("rows") == dst.get("rows")


class PostgresFamilyAdapter(DbApiRdbAdapter):
    name = "postgres-family"
    data_source_types = (
        "PostgreSQL",
        "PolarDBPg",
        "AuroraPostgreSQL",
        "Greenplum",
        "Cloudberry",
        "Redshift",
        "GaussDBForOpenGauss",
        "GaussDB",
        "KingbaseES",
        "Vastbase",
        "Hologres",
    )
    source_data_types = data_source_types
    target_data_types = data_source_types
    driver_modules = ("psycopg",)
    install_commands = ("python3 -m pip install psycopg[binary]",)
    default_profile = "postgres-core-4"
    data_model = "rdb-postgres-protocol"
    default_database = "postgres"

    def _connect(self, ds, password, user=None, db=None, host_type=None, host=None):
        self.require_dependencies()
