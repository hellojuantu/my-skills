class Db2FamilyAdapter(DbApiRdbAdapter):
    name = "db2-family"
    data_source_types = ("Db2",)
    source_data_types = data_source_types
    target_data_types = data_source_types
    driver_modules = ("ibm_db", "ibm_db_dbi")
    install_commands = ("python3 -m pip install ibm_db",)
    default_profile = "db2-core-4"
    data_model = "rdb-db2"
    auto_id_type = "INTEGER GENERATED BY DEFAULT AS IDENTITY"

    def _connect(self, ds, password, user=None, db=None, host_type=None, host=None):
        self.require_dependencies()
        import ibm_db_dbi

        resolved_host, port = self._host_port(ds, host_type, host)
        database = db or self._ds_database(ds)
        conn_str = "DATABASE={};HOSTNAME={};PORT={};PROTOCOL=TCPIP;UID={};PWD={};".format(database, resolved_host, port, self._account(ds, user), password)
