    data_model = "rdb-oracle"
    paramstyle = "numeric"
    auto_id_type = "NUMBER GENERATED BY DEFAULT AS IDENTITY"
    int_type = "NUMBER(10)"
    code_type = "VARCHAR2(64)"
    varchar_type = "VARCHAR2(255)"
    timestamp_type = "TIMESTAMP"

    def _connect(self, ds, password, user=None, db=None, host_type=None, host=None):
        self.require_dependencies()
        import oracledb

        resolved_host, port = self._host_port(ds, host_type, host)
