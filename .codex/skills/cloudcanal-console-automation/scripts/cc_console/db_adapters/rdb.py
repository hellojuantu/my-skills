class ClickHouseFamilyAdapter(DatabaseAdapter):
    name = "clickhouse-family"
    data_source_types = ("ClickHouse",)
    source_data_types = data_source_types
    target_data_types = data_source_types
    driver_modules = ("clickhouse_connect",)
    install_commands = ("python3 -m pip install clickhouse-connect",)
    default_profile = "clickhouse-core-4"
    data_model = "rdb-clickhouse"
    can_init_source = True
    can_prepare_target = True
    can_cleanup = True
    can_faker_crud = True
    can_compare = True

    def _quote_ident(self, name):
        return "`" + str(name).replace("`", "``") + "`"

    def _qname(self, schema, table):
        return self._quote_ident(schema) + "." + self._quote_ident(table)

    def _client(self, ds, password, user=None, host_type=None, host=None):
        self.require_dependencies()
        import clickhouse_connect

        resolved_host, port = parse_host_port((host or choose_test_host(ds, host_type, host)[0]), default_port("ClickHouse"))
        return clickhouse_connect.get_client(host=resolved_host, port=port, username=user or ds.get("accountName"), password=password)

    def profile_tables(self, profile):
        if profile != self.default_profile:
            raise AdapterCapabilityError("unsupported " + self.name + " profile: " + str(profile))
        return list(CORE_TABLES)

    def _create_table_sql(self, schema, table):
        id_type = "Int32"
        if table == "pk_varchar_table":
            id_type = "String"
        elif table == "pk_timestamp_table":
            id_type = "DateTime"
        return "CREATE TABLE " + self._qname(schema, table) + " (id " + id_type + ", code String, amount Decimal(18,2), payload String, updated_at DateTime DEFAULT now(), PRIMARY KEY id) ENGINE = MergeTree ORDER BY id"

    def init_source_dataset(self, ds, password, schema, rows, profile, drop_existing, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        client = self._client(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        if drop_existing:
            client.command("DROP DATABASE IF EXISTS " + self._quote_ident(schema))
        client.command("CREATE DATABASE IF NOT EXISTS " + self._quote_ident(schema))
        for table in self.profile_tables(profile):
            client.command("DROP TABLE IF EXISTS " + self._qname(schema, table))
            client.command(self._create_table_sql(schema, table))
            self._seed_clickhouse(client, schema, table, rows)
        return {"schema": schema, "profile": profile, "tables": self.profile_tables(profile), "seedRowsPerTable": rows}

    def prepare_target_dataset(self, ds, password, schema, drop_existing, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        client = self._client(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        if drop_existing:
            client.command("DROP DATABASE IF EXISTS " + self._quote_ident(schema))
        client.command("CREATE DATABASE IF NOT EXISTS " + self._quote_ident(schema))
        return {"schema": schema}

    def cleanup_dataset(self, ds, password, schema, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        client = self._client(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        client.command("DROP DATABASE IF EXISTS " + self._quote_ident(schema))
        return {"schema": schema, "dropped": True}

    def _seed_clickhouse(self, client, schema, table, rows):
        data = []
        base = datetime(2026, 1, 1, 0, 0, 0)
        for i in range(1, rows + 1):
            if table == "pk_varchar_table":
                pk = "vk_" + str(i)
            elif table == "pk_timestamp_table":
                pk = base + timedelta(seconds=i)
            else:
                pk = i
            data.append((pk, "code_" + str(i), i * 1.11, "seed-" + table + "-" + str(i)))
        client.insert(self._qname(schema, table), data, column_names=["id", "code", "amount", "payload"])

    def faker_crud(self, ds, password, schema, rounds, profile, seed, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        rng = random.Random(seed)
        client = self._client(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        stats = {table: {"insert": 0, "update": 0, "delete": 0, "skippedDuplicate": 0} for table in self.profile_tables(profile)}
        changed = 0
        for i in range(1, rounds + 1):
            table = rng.choice(self.profile_tables(profile))
            marker = "crud-" + str(seed) + "-" + str(i)
            if table == "pk_varchar_table":
                pk = "crud_vk_" + str(i)
            elif table == "pk_timestamp_table":
                pk = datetime(2027, 1, 1, 0, 0, 0) + timedelta(seconds=i)
            else:
                pk = 100000 + i
            client.insert(self._qname(schema, table), [(pk, marker, i * 2.22, marker)], column_names=["id", "code", "amount", "payload"])
            stats[table]["insert"] += 1
            changed += 1
        return {"schema": schema, "profile": profile, "rounds": rounds, "seed": seed, "changedRows": changed, "stats": stats, "ok": changed > 0}

    def table_snapshot(self, ds, password, schema, table, check_mode, allow_non_temp, **kwargs):
        require_temp_schema(schema, allow_non_temp)
        client = self._client(ds, password, user=kwargs.get("user"), host_type=kwargs.get("host_type"), host=kwargs.get("host"))
        if check_mode == "count":
            try:
                rows = client.query("SELECT COUNT(*) FROM " + self._qname(schema, table)).result_rows
                return {"exists": True, "rows": rows[0][0] if rows else 0}
            except Exception:
                return {"exists": False, "rows": 0}
        if check_mode != "digest":
            raise ValueError("unsupported check mode: " + str(check_mode))
        try:
            rows = client.query("SELECT * FROM " + self._qname(schema, table) + " ORDER BY id").result_rows
        except Exception:
            return {"exists": False, "rows": 0, "digest": None, "columns": []}
        digest = hashlib.sha256()
        for row in rows:
            digest.update(json_digest_row(row))
            digest.update(b"\n")
        return {"exists": True, "rows": len(rows), "digest": digest.hexdigest(), "columns": ["id", "code", "amount", "payload", "updated_at"]}

    def compare_datasets(self, source_ds, target_ds, source_password, target_password, source_schema, target_schema, profile, allow_non_temp, **kwargs):
        check_mode = kwargs.get("check_mode") or "count"
        result = {"sourceSchema": source_schema, "targetSchema": target_schema, "profile": profile, "checkMode": check_mode, "tables": [], "ignoredTables": [], "ok": True}
        for table in kwargs.get("tables") or self.profile_tables(profile):
            src = self.table_snapshot(source_ds, source_password, source_schema, table, check_mode, allow_non_temp, user=kwargs.get("source_user"), host_type=kwargs.get("source_host_type"), host=kwargs.get("source_host"))
            dst = self.table_snapshot(target_ds, target_password, target_schema, table, check_mode, allow_non_temp, user=kwargs.get("target_user"), host_type=kwargs.get("target_host_type"), host=kwargs.get("target_host"))
            ok = snapshots_equal(src, dst, check_mode)
            result["tables"].append({"table": table, "ok": ok, "source": src, "target": dst, "primaryKeyColumns": ["id"]})
            if not ok:
                result["ok"] = False
        return result


